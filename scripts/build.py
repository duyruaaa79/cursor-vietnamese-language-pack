#!/usr/bin/env python3
"""Build a Vietnamese Language Pack from the installed Cursor app."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from translate_vi import translate  # noqa: E402

CURSOR_APP = Path("/Applications/Cursor.app/Contents/Resources/app")


def load_json(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def dump_i18n(path: Path, contents: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "": [
            "--------------------------------------------------------------------------------------------",
            "Vietnamese Language Pack for Cursor. Generated from Cursor NLS catalogs.",
            "--------------------------------------------------------------------------------------------",
            "Do not edit this file. It is machine generated.",
        ],
        "version": "1.0.0",
        "contents": contents,
    }
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")


def translate_map(src: dict[str, str]) -> dict[str, str]:
    return {k: translate(v) if isinstance(v, str) else v for k, v in src.items()}


def build_main() -> tuple[dict, int, int]:
    keys = load_json(CURSOR_APP / "out" / "nls.keys.json")
    msgs = load_json(CURSOR_APP / "out" / "nls.messages.json")
    contents: dict[str, dict[str, str]] = {}
    i = 0
    translated = 0
    total = 0
    for module, module_keys in keys:
        bucket = {}
        for key in module_keys:
            en = msgs[i]
            vi = translate(en)
            bucket[key] = vi
            total += 1
            if vi != en:
                translated += 1
            i += 1
        contents[module] = bucket
    if i != len(msgs):
        raise SystemExit(f"NLS length mismatch: keys={i} msgs={len(msgs)}")
    return contents, translated, total


def extension_id(ext_dir: Path) -> str | None:
    pkg_path = ext_dir / "package.json"
    if not pkg_path.exists():
        return None
    pkg = load_json(pkg_path)
    name = pkg.get("name")
    publisher = pkg.get("publisher")
    if not name:
        return None
    if publisher:
        return f"{publisher}.{name}"
    return name


def build_extensions() -> list[dict[str, str]]:
    translations = []
    ext_root = CURSOR_APP / "extensions"
    if not ext_root.exists():
        return translations
    for nls_path in sorted(ext_root.glob("*/package.nls.json")):
        ext_dir = nls_path.parent
        ext_id = extension_id(ext_dir)
        if not ext_id:
            continue
        src = load_json(nls_path)
        contents = {"package": translate_map(src)}
        rel = Path("translations/extensions") / f"{ext_id}.i18n.json"
        dump_i18n(ROOT / rel, contents)
        translations.append({"id": ext_id, "path": f"./{rel.as_posix()}"})
    return translations


def write_package_json(ext_translations: list[dict[str, str]]) -> None:
    contrib = [
        {"id": "vscode", "path": "./translations/main.i18n.json"},
        *ext_translations,
    ]
    package = {
        "name": "cursor-vietnamese-language-pack",
        "displayName": "Vietnamese Language Pack for Cursor",
        "description": "Gói ngôn ngữ Tiếng Việt cho Cursor. Việt hóa menu, workbench, Git và chuỗi Cursor (Agent, Composer) lấy từ catalog NLS của ứng dụng.",
        "version": "0.1.0",
        "publisher": "duy",
        "license": "MIT",
        "engines": {"vscode": "^1.80.0"},
        "icon": "icon.png",
        "categories": ["Language Packs"],
        "keywords": ["vietnamese", "tiếng việt", "language pack", "i18n", "l10n", "cursor"],
        "scripts": {
            "build": "python3 scripts/build.py",
            "package": "python3 scripts/build.py && npx --yes @vscode/vsce package --allow-missing-repository",
        },
        "contributes": {
            "localizations": [
                {
                    "languageId": "vi",
                    "languageName": "Vietnamese",
                    "localizedLanguageName": "Tiếng Việt",
                    "translations": contrib,
                }
            ]
        },
        "repository": {
            "type": "git",
            "url": "https://github.com/duyruaaa79/cursor-vietnamese-language-pack",
        },
    }
    with (ROOT / "package.json").open("w", encoding="utf-8") as f:
        json.dump(package, f, ensure_ascii=False, indent=2)
        f.write("\n")


def write_icon() -> None:
    """Minimal 128×128 PNG: red field, yellow star-ish center (Vietnam-inspired)."""
    import struct
    import zlib

    w = h = 128
    rows = []
    cx = cy = 63.5
    for y in range(h):
        row = [0]
        for x in range(w):
            dx = (x - cx) / 22.0
            dy = (cy - y) / 22.0
            # 5-point star via polar test on a diamond+cross approximation
            ax, ay = abs(dx), abs(dy)
            in_star = (ax + ay * 1.7 < 1.15) or (ay + ax * 1.7 < 1.15)
            if in_star and (dx * dx + dy * dy) < 1.35:
                row += [218, 165, 32, 255]
            else:
                row += [218, 37, 29, 255]
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    (ROOT / "icon.png").write_bytes(png)


def main() -> None:
    if not CURSOR_APP.exists():
        raise SystemExit(f"Cursor not found at {CURSOR_APP}")
    print("Translating Cursor workbench NLS…")
    main_contents, translated, total = build_main()
    dump_i18n(ROOT / "translations" / "main.i18n.json", main_contents)
    print(f"  workbench: {translated}/{total} strings changed ({translated / total:.0%})")
    print("Translating built-in extension package.nls.json…")
    ext_translations = build_extensions()
    print(f"  extensions: {len(ext_translations)} packs")
    write_package_json(ext_translations)
    write_icon()
    print("Wrote package.json and icon.png")
    print("Done.")


if __name__ == "__main__":
    main()
