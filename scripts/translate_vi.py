def _keep_english(s: str) -> bool:
    t = s.strip()
    if not t:
        return True
    if re.fullmatch(r"[\d\s.,;:_\-+*/\\|%=<>()\[\]{}'\"`~!?@#$]+", t):
        return True
    if re.fullmatch(r"[A-Za-z0-9_./:-]+\.(json|js|ts|tsx|md|yml|yaml|css|html)", t):
        return True
    if re.fullmatch(r"[a-z]+(\.[A-Za-z0-9_-]+)+", t):
        return True
    letters = re.findall(r"[A-Za-z]", t)
    if not letters:
        return True
    return False


def _restore_mnemonic(original: str, translated: str) -> str:
    if "&&" not in original:
        return translated
    if "&&" in translated:
        return translated
    stripped = translated.lstrip()
    if not stripped:
        return translated
    return "&&" + stripped


def _apply_phrases(text: str) -> str:
    def repl(m: re.Match[str]) -> str:
        key = m.group(1).lower()
        return PHRASES.get(key, m.group(1))

    return _PHRASE_RE.sub(repl, text)


def _apply_words(text: str) -> str:
    parts = re.split(r"([A-Za-z']+)", text)

    def conv(token: str) -> str:
        if not token or not token[0].isalpha():
            return token
        low = token.lower()
        if low in WORDS:
            out = WORDS[low]
            if not out:
                return ""
            if token.isupper() and len(token) > 1:
                return out
            if token[0].isupper():
                return out[:1].upper() + out[1:]
            return out
        return token

    joined = "".join(conv(p) for p in parts)
    return re.sub(r" {2,}", " ", joined).strip()


def _word_count(text: str) -> int:
    return len(re.findall(r"[A-Za-z']+", text))


