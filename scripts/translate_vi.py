def translate(text: str) -> str:
    if text is None:
        return text
    if text in EXACT:
        return EXACT[text]
    if _keep_english(text):
        return text

    had_mnemonic = "&&" in text
    work = text.replace("&&", "")

    tokens: list[str] = []

    def stash(m: re.Match[str]) -> str:
        tokens.append(m.group(0))
        return f"\u0000{len(tokens) - 1}\u0000"

    work = _PLACEHOLDER.sub(stash, work)
    key = re.sub(r"\s+", " ", work.strip().lower())
    if key in PHRASES:
        out = PHRASES[key]
    elif not EXACT and _word_count(work) <= 5:
        out = _apply_phrases(work)
        out = _apply_words(out)
    else:
        # Without a reviewed translation, English beats word-by-word Vietnamese
        # with the wrong word order.
        return text

    def unstash(m: re.Match[str]) -> str:
        return tokens[int(m.group(1))]

    out = re.sub(r"\x00(\d+)\x00", unstash, out)
    out = re.sub(r" {2,}", " ", out).strip()
    if not out:
        return text
    if had_mnemonic:
        out = _restore_mnemonic(text, out)
    if text.endswith("...") and not out.endswith("..."):
        out += "..."
    if text.endswith(":") and not out.endswith(":"):
        out += ":"
    return out
